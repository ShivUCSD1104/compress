#!/usr/bin/env python3
"""Build a native binary and a checksum-pinned local Homebrew formula."""
import hashlib
from pathlib import Path
import platform
import subprocess
import tarfile

root = Path(__file__).resolve().parents[1]
subprocess.run(['cargo', 'build', '--release', '--locked', '--offline'], cwd=root, check=True)
version = subprocess.check_output([str(root / 'target/release/compress'), '--version'], text=True).split()[1]
system = platform.system()
if system not in ('Darwin', 'Linux'):
    raise SystemExit('Only macOS and Linux are supported')
arch = {'arm64': 'arm64', 'aarch64': 'arm64', 'x86_64': 'x86_64'}[platform.machine()]
dist = root / 'dist'; dist.mkdir(exist_ok=True)
archive = dist / f'compress-cli-{version}-{system.lower()}-{arch}.tar.gz'
with tarfile.open(archive, 'w:gz') as tar:
    tar.add(root / 'target/release/compress', arcname='compress')
    tar.add(root / 'LICENSE', arcname='LICENSE')
sha = hashlib.sha256(archive.read_bytes()).hexdigest()
formula = f'''# Generated by scripts/package-homebrew.py for this machine.
# To distribute, host the archive and replace its file URL with the release URL.
class CompressCli < Formula
  desc "PDF and image compression with simple quality presets"
  url "{archive.as_uri()}"
  version "{version}"
  sha256 "{sha}"
  license "MIT"

  depends_on :{'macos' if system == 'Darwin' else 'linux'}
  depends_on arch: :{arch}
  depends_on "jpegoptim"
  depends_on "oxipng"
  depends_on "qpdf"
  depends_on "ghostscript"

  def install
    bin.install "compress"
  end

  test do
    assert_match "compress {version}", shell_output("#{{bin}}/compress --version")
    assert_match "Usage:", shell_output("#{{bin}}/compress --help")
    (testpath/"unsupported.txt").write("hello")
    assert_match "unsupported format", shell_output("#{{bin}}/compress unsupported.txt 2>&1", 1)
  end
end
'''
(root / 'Formula/compress-cli.rb').write_text(formula)
print(root / 'Formula/compress-cli.rb')
